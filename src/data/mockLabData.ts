export interface LabEvaluationResult {
  numericValue?: number;
  resultClean: string;
  configuredCriteria: string;
  compliance: ComplianceStatus;
  complianceNote: string;
  healthRisk: HealthRiskLevel;
  healthRiskDescription: string;
}

export function evaluateLabResult(
  paramIdOrName: string,
  rawResult: string,
  customConfiguredCriteria?: string
): LabEvaluationResult {
  const clean = rawResult.trim();
  const lower = clean.toLowerCase();

  // Find standard definition by id or name
  const def = STANDARD_LAB_PARAMETERS.find(
    (p) =>
      p.id.toLowerCase() === paramIdOrName.toLowerCase() ||
      p.name.toLowerCase() === paramIdOrName.toLowerCase()
  );

  const criteriaToUse =
    customConfiguredCriteria?.trim() ||
    def?.normativeLimit ||
    'Sin norma configurada';

  // Rule: "No asumir que un resultado es legal o ilegal si no existe una norma configurada."
  const hasNoConfiguredNorm =
    criteriaToUse === 'Sin norma configurada' ||
    criteriaToUse.toLowerCase().includes('sin norma') ||
    (!def?.maxVal && !def?.minVal && !def?.mustBeAbsent && !def?.isReferential && !customConfiguredCriteria);

  if (!clean) {
    return {
      resultClean: '',
      configuredCriteria: criteriaToUse,
      compliance: hasNoConfiguredNorm ? 'sin_norma' : 'referencial',
      complianceNote: hasNoConfiguredNorm ? 'Sin norma configurada (No regulado)' : 'Sin resultado ingresado',
      healthRisk: 'sin_riesgo',
      healthRiskDescription: 'Pendiente de determinación analítica.',
    };
  }

  if (hasNoConfiguredNorm) {
    const parsedNum = parseFloat(clean.replace(',', '.'));
    return {
      numericValue: isNaN(parsedNum) ? undefined : parsedNum,
      resultClean: clean,
      configuredCriteria: 'Sin norma configurada (No regulado)',
      compliance: 'sin_norma',
      complianceNote: `Resultado analítico registrado: ${clean} ${def?.defaultUnit || ''}. NOTA: No existe una norma legal configurada; por lo tanto, no se asume legalidad ni ilegalidad.`,
      healthRisk: 'sin_riesgo',
      healthRiskDescription: 'Determinación cuantitativa de elemento traza sin estándar legal de contraste.',
    };
  }

  // Handle qualitative negative responses (Ausente, Negativo, 0, < 1, etc.)
  const isQualitativeAbsent =
    lower.includes('ausente') ||
    lower === '0' ||
    lower.includes('no detect') ||
    lower === '<1' ||
    lower === '< 1' ||
    lower === '<0.1' ||
    lower === 'negativo';

  if (isQualitativeAbsent) {
    return {
      numericValue: 0,
      resultClean: clean,
      configuredCriteria: criteriaToUse,
      compliance: 'cumple',
      complianceNote: `CUMPLE D.S. N.° 031-2010-SA (Ausencia total comprobada: ${clean})`,
      healthRisk: 'sin_riesgo',
      healthRiskDescription:
        def?.healthRiskNormal || 'Inocuidad garantizada en el ensayo analítico.',
    };
  }

  // Handle qualitative positive responses for pathogens
  if (lower.includes('presente') || lower.includes('positivo') || lower.includes('detectado')) {
    return {
      resultClean: clean,
      configuredCriteria: criteriaToUse,
      compliance: 'no_cumple',
      complianceNote: `NO CUMPLE D.S. N.° 031-2010-SA: Presencia detectada (${clean}) cuando el límite exige Ausencia Total (0).`,
      healthRisk: def?.alertSeverity || 'riesgo_critico',
      healthRiskDescription:
        def?.healthRiskAlert ||
        'PELIGRO SANITARIO: Hallazgo biológico o químico positivo fuera de norma.',
    };
  }

  const num = parseFloat(clean.replace(',', '.'));

  // If not a number
  if (isNaN(num)) {
    return {
      resultClean: clean,
      configuredCriteria: criteriaToUse,
      compliance: 'referencial',
      complianceNote: `Resultado cualitativo: "${clean}". Cotejar con criterio: ${criteriaToUse}`,
      healthRisk: 'sin_riesgo',
      healthRiskDescription: 'Parámetro reportado en escala cualitativa.',
    };
  }

  // Purely referential parameters without strict LMP (e.g. Temperatura in situ)
  if (def?.isReferential) {
    return {
      numericValue: num,
      resultClean: clean,
      configuredCriteria: criteriaToUse,
      compliance: 'referencial',
      complianceNote: `Parámetro físico ambiental referencial in situ (${clean} ${def.defaultUnit})`,
      healthRisk: 'sin_riesgo',
      healthRiskDescription: def.healthRiskNormal,
    };
  }

  // Must be absent check (num > 0)
  if (def?.mustBeAbsent && num > 0) {
    return {
      numericValue: num,
      resultClean: clean,
      configuredCriteria: criteriaToUse,
      compliance: 'no_cumple',
      complianceNote: `NO CUMPLE D.S. N.° 031-2010-SA: Se detectaron ${num} ${def.defaultUnit}, excediendo el límite normativo de 0 (Ausencia).`,
      healthRisk: def.alertSeverity,
      healthRiskDescription: def.healthRiskAlert,
    };
  }

  // Min value check (e.g., pH < 6.5 or Cloro < 0.50)
  if (def?.minVal !== undefined && num < def.minVal) {
    return {
      numericValue: num,
      resultClean: clean,
      configuredCriteria: criteriaToUse,
      compliance: 'no_cumple',
      complianceNote: `NO CUMPLE D.S. N.° 031-2010-SA: Valor inferior al límite mínimo permitido (${num} < ${def.minVal} ${def.defaultUnit}).`,
      healthRisk: def.alertSeverity,
      healthRiskDescription: def.healthRiskAlert,
    };
  }

  // Max value check (e.g., pH > 8.5, Turbidez > 5.0, Conductividad > 1500, etc.)
  if (def?.maxVal !== undefined && num > def.maxVal) {
    return {
      numericValue: num,
      resultClean: clean,
      configuredCriteria: criteriaToUse,
      compliance: 'no_cumple',
      complianceNote: `NO CUMPLE D.S. N.° 031-2010-SA: Supera el Límite Máximo Permisible (${num} > ${def.maxVal} ${def.defaultUnit}).`,
      healthRisk: def.alertSeverity,
      healthRiskDescription: def.healthRiskAlert,
    };
  }

  // Everything within limits!
  return {
    numericValue: num,
    resultClean: clean,
    configuredCriteria: criteriaToUse,
    compliance: 'cumple',
    complianceNote: `CUMPLE D.S. N.° 031-2010-SA: Concentración dentro del Límite Máximo Permisible (${criteriaToUse}).`,
    healthRisk: 'sin_riesgo',
    healthRiskDescription:
      def?.healthRiskNormal ||
      'Parámetro analítico conforme a los estándares de calidad ambiental para agua potable.',
  };
}

export function checkLabCompliance(paramName: string, rawResult: string): { compliant: boolean | null; note: string } {
  const evalRes = evaluateLabResult(paramName, rawResult);
  if (evalRes.compliance === 'cumple') return { compliant: true, note: evalRes.complianceNote };
  if (evalRes.compliance === 'no_cumple') return { compliant: false, note: evalRes.complianceNote };
  return { compliant: null, note: evalRes.complianceNote };
}


